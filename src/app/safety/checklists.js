const ck = (c) =>
  Object.assign({ kind: "vehicle" }, c, {
    asset: c.asset || c.reg || "",
    reading: c.reading ?? c.mileage ?? "",
  });
function defectsOf(c) {
  const k = KINDS[ck(c).kind] || KINDS.vehicle;
  return k.items
    .filter(([key]) => c.items && c.items[key] === "defect")
    .map(([, l]) => l.split(":")[0]);
}
const hasProblem = (c) => defectsOf(c).length > 0 || c.safe === false;
